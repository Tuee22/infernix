-- | Convert a wire 'Natural' into the platform 'Int' the domain types use.
--
-- Phase 8 Sprint 8.9 moved every generated quantity from Dhall @Integer@ to
-- @Natural@, so a negative quantity is no longer representable in the wire
-- language at all rather than being rejected after decode. What @Natural@ does
-- not bound is the top: fail closed on a value the platform integer cannot hold
-- instead of wrapping it into a small positive one.
naturalToInt :: String -> Natural -> Either String Int
naturalToInt fieldPath value
  | toInteger value > toInteger (maxBound :: Int) =
      Left (fieldPath <> " exceeds the supported integer range: " <> show value)
  | otherwise = Right (fromIntegral value)

dhallInterpretOptions :: Dhall.InterpretOptions
dhallInterpretOptions =
