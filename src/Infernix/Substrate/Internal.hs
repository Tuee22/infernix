dhallList :: String -> (a -> String) -> [a] -> String
dhallList itemType renderItem values =
  case values of
    [] -> "([] : List " <> itemType <> ")"
    _ -> "[ " <> intercalate ", " (map renderItem values) <> " ]"

dhallBool :: Bool -> String
dhallBool value
  | value = "True"
  | otherwise = "False"

-- | Render a generated quantity as a Dhall @Natural@ literal.
--
-- Every call site renders a value whose non-negativity was already established
-- by a checked constructor or a compiler check: 'mkHostMemoryPartition' rejects
-- a non-positive physical size, a negative reserve, or a pool too small for its
-- derived co-tenant headroom,
-- 'mkModelMemoryFootprint' requires a positive footprint, @InvalidPoolMaxInflight@
-- rejects a non-positive inflight bound, and 'podMemoryLimitFromDhall' plus
-- config validation require a positive limit. A negative value would render as
-- an @Integer@ literal and fail the very next decode rather than round-tripping
-- silently.
dhallNatural :: Int -> String
dhallNatural = show

dhallFilePath :: FilePath -> String
dhallFilePath = dhallText . Text.pack

dhallText :: Text -> String
dhallText value =
  Text.unpack ("\"" <> DhallCore.escapeText value <> "\"")

