-- | The one mirror that cannot use the generic derivation.
--
-- @genericAutoWith@ dispatches on the datatype's GHC-Generics shape, and a
-- single-constructor type has no @:+:@ at all, so it derives as a /record/ —
-- here the empty record @{}@ — rather than as a one-alternative union. Building
-- the union decoder explicitly keeps the wire shape @< TextField >@, so adding
-- a second request-field type later is a wire addition rather than a wire
-- rewrite. The round-trip through the real decode boundary is what catches this;
-- the annotation and the decoder are otherwise unrelated.
data DhallRequestFieldType
  = DhallRequestFieldTypeTextField

instance Dhall.FromDhall DhallRequestFieldType where
  autoWith _ =
    Dhall.union (DhallRequestFieldTypeTextField <$ Dhall.constructor "TextField" Dhall.unit)

