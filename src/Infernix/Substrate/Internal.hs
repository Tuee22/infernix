dhallFieldName :: Text -> Text
-- Phase 8 Sprint 8.9 removed the @legacyDhall@ prefix branch: the pre-union
-- decoder it served is gone and no field carried that prefix any more, so the
-- branch was dead compatibility residue rather than a supported spelling.
dhallFieldName rawFieldName =
  maybe rawFieldName dhallFieldSuffixName (Text.stripPrefix "dhall" rawFieldName)

dhallFieldSuffixName :: Text -> Text
dhallFieldSuffixName suffix =
  case suffix of
    "ConfigRuntimeMode" -> "runtimeMode"
    "DemoUi" -> "demo_ui"
    "ModelsBucket" -> "models_bucket"
    "ModelBootstrapTopic" -> "model_bootstrap_topic"
    "InferenceMemoryBudget" -> "inferenceMemoryBudget"
    "BudgetPhysicalMib" -> "physicalMib"
    "BudgetVmReserveMib" -> "vmReserveMib"
    "BudgetLimitMib" -> "limitMib"
    "BudgetPodLimit" -> "podLimit"
    "BudgetVramLimit" -> "vramLimit"
    "ExecutionShape" -> "executionShape"
    "ShapeContextLength" -> "contextLength"
    "ShapeBatchSize" -> "batchSize"
    "ShapeGenerationBound" -> "generationBound"
    "ShapeCacheElementWidth" -> "cacheElementWidth"
    "ShapeLoadStrategy" -> "loadStrategy"
    "GeometryLayers" -> "layers"
    "GeometryKeyValueHeads" -> "keyValueHeads"
    "GeometryHeadWidth" -> "headWidth"
    "GeometryHiddenWidth" -> "hiddenWidth"
    "EnginePools" -> "enginePools"
    "PoolId" -> "id"
    "PoolMemberIds" -> "members"
    "PoolSubscriptionType" -> "subscription"
    "PoolModels" -> "models"
    other -> lowerInitial other

lowerInitial :: Text -> Text
lowerInitial value =
  case Text.uncons value of
    Nothing -> value
    Just (firstCharacter, rest) -> Text.cons (toLower firstCharacter) rest

-- | Rebuild the domain configuration from the reduced wire.
--
-- Phase 8 Sprint 8.10: every field this reconstructs was previously carried on
-- the wire as a second copy of a fact the binary already derives. Dhall record
-- types are not dependent — a field's type can never mention a sibling's value —
-- so any pair of fields that must agree is a permanent illegal-state generator.
-- Deriving them here is the only shape with no disagreement left to detect,
-- which is why the equality checks that existed to catch such a disagreement are
-- retired with the fields rather than before them.
demoConfigFromDhall :: DhallDemoConfig -> Either String DemoConfig
demoConfigFromDhall rawConfig = do
  let runtimeModeValue = runtimeModeFromDhall (dhallConfigRuntimeMode rawConfig)
  decodedPools <- traverse (enginePoolFromDhall runtimeModeValue) (dhallEnginePools rawConfig)
  memoryBudgetValue <-
    inferenceMemoryBudgetFromDhall runtimeModeValue (dhallInferenceMemoryBudget rawConfig)
  pure
    DemoConfig
      { configRuntimeMode = runtimeModeValue,
        configMapName = dhallConfigMapName rawConfig,
        generatedPath = Text.unpack (dhallGeneratedPath rawConfig),
        mountedPath = Text.unpack (dhallMountedPath rawConfig),
        demoUiEnabled = dhallDemoUi rawConfig,
        configPoolCatalogs =
          [ PoolCatalog
              { poolCatalogId = enginePoolId pool,
                poolCatalogMemberIds = enginePoolMemberIds pool,
                poolCatalogSubscriptionType = enginePoolSubscriptionType pool,
                poolCatalogModels = poolModels
              }
          | (pool, poolModels) <- decodedPools
          ],
        modelsBucket = dhallModelsBucket rawConfig,
        modelBootstrapTopic = dhallModelBootstrapTopic rawConfig,
        inferenceMemoryBudget = memoryBudgetValue
      }

inferenceMemoryBudgetFromDhall ::
  RuntimeMode ->
  DhallInferenceMemoryBudget ->
  Either String InferenceMemoryBudget
inferenceMemoryBudgetFromDhall runtimeModeValue rawBudget =
  case rawBudget of
    HostEnforced hostBudget -> do
      physicalMib <-
        naturalToInt "inferenceMemoryBudget.physicalMib" (dhallBudgetPhysicalMib hostBudget)
      vmReserveMib <-
        naturalToInt "inferenceMemoryBudget.vmReserveMib" (dhallBudgetVmReserveMib hostBudget)
      HostEnforcedBudget <$> mkHostMemoryPartition physicalMib vmReserveMib
    SubstrateEnforced substrateBudget ->
      SubstrateEnforcedBudget
        <$> podMemoryLimitFromDhall
          "inferenceMemoryBudget"
          PodRam
          (residentLimitSourceForMode runtimeModeValue)
          substrateBudget
    DualEnforced dualBudget ->
      DualEnforcedBudget
        <$> podMemoryLimitFromDhall
          "inferenceMemoryBudget.podLimit"
          PodRam
          (residentLimitSourceForMode runtimeModeValue)
          (dhallBudgetPodLimit dualBudget)
        <*> podMemoryLimitFromDhall
          "inferenceMemoryBudget.vramLimit"
          NvidiaVram
          LinuxGpuVramBudget
          (dhallBudgetVramLimit dualBudget)

-- | Which policy set a resident-memory limit. Only the cluster engine pod limit
-- has ever named one; the VRAM half names its own source at its own call site.
residentLimitSourceForMode :: RuntimeMode -> PodMemoryLimitSource
residentLimitSourceForMode _ = ClusterEnginePodMemoryLimit

podMemoryLimitFromDhall ::
  String ->
  Resource ->
  PodMemoryLimitSource ->
  DhallSubstrateMemoryBudget ->
  Either String PodMemoryLimit
podMemoryLimitFromDhall fieldPath limitResource sourceValue substrateBudget = do
  limitMib <- naturalToInt (fieldPath <> ".limitMib") (dhallBudgetLimitMib substrateBudget)
  -- @Natural@ already excludes a negative limit on the wire; zero is still
  -- representable, so the positivity check stays.
  if limitMib <= 0
    then Left (fieldPath <> ".limitMib must be positive")
    else
      pure
        PodMemoryLimit
          { podMemoryLimitResource = limitResource,
            podMemoryLimitSource = sourceValue,
            podMemoryLimitMib = limitMib
          }

enginePoolFromDhall :: RuntimeMode -> DhallEnginePool -> Either String (EnginePool, [ModelDescriptor])
enginePoolFromDhall runtimeModeValue rawPool = do
  poolModels <- traverse (modelDescriptorFromDhall runtimeModeValue) (dhallPoolModels rawPool)
  pure
    ( EnginePool
        { enginePoolId = dhallPoolId rawPool,
          enginePoolRuntimeMode = runtimeModeValue,
          enginePoolModelIds = map modelId poolModels,
          enginePoolMemberIds = dhallPoolMemberIds rawPool,
          enginePoolSubscriptionType =
            consumerSubscriptionFromDhall (dhallPoolSubscriptionType rawPool),
          enginePoolMaxInflightPerMember = defaultMaxInflightPerMember
        },
      poolModels
    )

modelDescriptorFromDhall :: RuntimeMode -> DhallModelDescriptor -> Either String ModelDescriptor
modelDescriptorFromDhall runtimeModeValue rawModel = do
  requestShapeValue <- traverse requestFieldFromDhall (dhallRequestShape rawModel)
  -- Phase 4 Sprint 4.39: the shape's quantities are required and positive, and
  -- the load strategy is what decides whether the model uses the device at all.
  shapeValue <- modelExecutionShapeFromDhall (dhallModelId rawModel) (dhallExecutionShape rawModel)
  geometryValue <-
    traverse (modelGeometryFromDhall (dhallModelId rawModel)) (dhallGeometry rawModel)
  let runtimeLaneValue =
        runtimeLaneForMode
          runtimeModeValue
          (executionLoadStrategy shapeValue == StreamWeightsToDevice)
  pure
    ModelDescriptor
      { matrixRowId = dhallMatrixRowId rawModel,
        modelId = dhallModelId rawModel,
        displayName = dhallDisplayName rawModel,
        family = dhallFamily rawModel,
        description = dhallDescription rawModel,
        artifactType = dhallArtifactType rawModel,
        referenceModel = dhallReferenceModel rawModel,
        downloadUrl = dhallDownloadUrl rawModel,
        selectedEngine = dhallSelectedEngine rawModel,
        requestShape = requestShapeValue,
        runtimeMode = runtimeModeValue,
        runtimeLane = runtimeLaneValue,
        notes = dhallNotes rawModel,
        modelExecutionShape = shapeValue,
        modelGeometry = geometryValue
      }

modelExecutionShapeFromDhall ::
  Text ->
  DhallModelExecutionShape ->
  Either String ModelExecutionShape
modelExecutionShapeFromDhall modelIdValue rawShape = do
  contextLength <- shapeNatural "contextLength" (dhallShapeContextLength rawShape)
  batchSize <- shapeNatural "batchSize" (dhallShapeBatchSize rawShape)
  generationBound <- shapeNatural "generationBound" (dhallShapeGenerationBound rawShape)
  cacheElementWidth <- shapeNatural "cacheElementWidth" (dhallShapeCacheElementWidth rawShape)
  pure
    ModelExecutionShape
      { executionContextLength = contextLength,
        executionBatchSize = batchSize,
        executionGenerationBound = generationBound,
        executionCacheElementWidth = cacheElementWidth,
        executionLoadStrategy = loadStrategyFromDhall (dhallShapeLoadStrategy rawShape)
      }
  where
    shapeNatural fieldName =
      naturalToInt
        ("models." <> Text.unpack modelIdValue <> ".executionShape." <> fieldName)

loadStrategyFromDhall :: DhallModelLoadStrategy -> ModelLoadStrategy
loadStrategyFromDhall rawStrategy =
  case rawStrategy of
    DhallModelLoadStrategyLoadResidentHost -> LoadResidentHost
    DhallModelLoadStrategyStreamWeightsToDevice -> StreamWeightsToDevice

modelGeometryFromDhall :: Text -> DhallModelGeometry -> Either String ModelGeometry
modelGeometryFromDhall modelIdValue rawGeometry = do
  layers <- geometryNatural "layers" (dhallGeometryLayers rawGeometry)
  keyValueHeads <- geometryNatural "keyValueHeads" (dhallGeometryKeyValueHeads rawGeometry)
  headWidth <- geometryNatural "headWidth" (dhallGeometryHeadWidth rawGeometry)
  hiddenWidth <- geometryNatural "hiddenWidth" (dhallGeometryHiddenWidth rawGeometry)
  pure
    ModelGeometry
      { geometryLayers = layers,
        geometryKeyValueHeads = keyValueHeads,
        geometryHeadWidth = headWidth,
        geometryHiddenWidth = hiddenWidth
      }
  where
    geometryNatural fieldName =
      naturalToInt
        ("models." <> Text.unpack modelIdValue <> ".geometry." <> fieldName)

requestFieldFromDhall :: DhallRequestField -> Either String RequestField
requestFieldFromDhall rawField =
  pure
    RequestField
      { name = dhallName rawField,
        label = dhallLabel rawField,
        fieldType = requestFieldTypeFromDhall (dhallFieldType rawField)
      }

